def hex_with_alpha(hex_color: str, alpha: float) -> str:
    """Append hex alpha byte to a #rrggbb color."""
    if not hex_color or not hex_color.startswith("#"):
        return "#ffffff22"
    clean = hex_color[1:7]
    alpha_int = max(0, min(255, int(alpha * 255)))
    return f"#{clean}{alpha_int:02x}"


def shade_hex(hex_str: str, factor: float) -> str:
    """Darken or lighten a hex color by a factor preserving hue."""
    if not hex_str or not hex_str.startswith("#"):
        return "#0a0a0d"
    clean = hex_str[1:7]
    try:
        r = int(clean[0:2], 16)
        g = int(clean[2:4], 16)
        b = int(clean[4:6], 16)
        nr = max(0, min(255, int(r * factor)))
        ng = max(0, min(255, int(g * factor)))
        nb = max(0, min(255, int(b * factor)))
        return f"#{nr:02x}{ng:02x}{nb:02x}"
    except Exception:
        return hex_str


