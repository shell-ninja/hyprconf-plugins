def read_json_lenient(path: Path) -> dict:
    """Read a JSON file, handling simple comments or empty files."""
    if not path.exists():
        return {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            content = f.read().strip()
            if not content:
                return {}
            lines = []
            for line in content.splitlines():
                stripped = line.strip()
                if stripped.startswith("//") or stripped.startswith("/*"):
                    continue
                lines.append(line)
            return json.loads("\n".join(lines))
    except Exception:
        try:
            with open(path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}


def write_json_inplace(path: Path, data: dict):
    """Write data to path in-place preserving file inode for Linux inotify watchers."""
    path.parent.mkdir(parents=True, exist_ok=True)
    content = json.dumps(data, indent=4) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
        f.flush()
        os.fsync(f.fileno())


def backup_settings_if_needed(target_key: str, settings_path: Path):
    """Store an untouched original copy of user settings before any sync."""
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    backup_file = BACKUP_DIR / f"{target_key}_settings.json.orig"
    if not backup_file.exists() and settings_path.exists():
        try:
            shutil.copy2(settings_path, backup_file)
        except Exception:
            pass


def sync_editor_target(target_key: str, target_info: dict, colors: dict, config: dict) -> bool:
    """Inject customizations into a single editor's settings.json."""
    settings_path = target_info["settings_path"]
    if not settings_path.parent.exists():
        return False

    backup_settings_if_needed(target_key, settings_path)

    settings = read_json_lenient(settings_path)

    color_customizations = generate_color_customizations(colors, config)
    token_customizations = generate_token_customizations(colors) if config.get("sync_syntax", True) else None

    # Apply both root and theme-scoped rules (e.g. [Catppuccin Mocha], [*])
    current_theme = settings.get("workbench.colorTheme")
    applied_customizations = dict(color_customizations)
    applied_customizations["[*]"] = dict(color_customizations)
    if current_theme:
        applied_customizations[f"[{current_theme}]"] = dict(color_customizations)

    settings["workbench.colorCustomizations"] = applied_customizations

    if token_customizations:
        applied_tokens = dict(token_customizations)
        applied_tokens["[*]"] = dict(token_customizations)
        if current_theme:
            applied_tokens[f"[{current_theme}]"] = dict(token_customizations)
        settings["editor.tokenColorCustomizations"] = applied_tokens
    elif "editor.tokenColorCustomizations" in settings and settings.get("hyprconf.theme.synced"):
        settings.pop("editor.tokenColorCustomizations", None)

    # Sentinel tags
    settings["hyprconf.theme.synced"] = True
    settings["hyprconf.theme.timestamp"] = datetime.now().isoformat()
    settings["hyprconf.theme.version"] = "1.0.3"

    try:
        write_json_inplace(settings_path, settings)
        return True
    except Exception as e:
        print(f"[Error] Failed to write settings to {settings_path}: {e}", file=sys.stderr)
        return False


def restore_editor_target(target_key: str, target_info: dict) -> bool:
    """Cleanly remove Hyprconf theme customizations and restore original settings."""
    settings_path = target_info["settings_path"]
    backup_file = BACKUP_DIR / f"{target_key}_settings.json.orig"

    if backup_file.exists():
        try:
            shutil.copy2(backup_file, settings_path)
            return True
        except Exception:
            pass

    if settings_path.exists():
        settings = read_json_lenient(settings_path)
        settings.pop("workbench.colorCustomizations", None)
        settings.pop("editor.tokenColorCustomizations", None)
        settings.pop("hyprconf.theme.synced", None)
        settings.pop("hyprconf.theme.timestamp", None)
        settings.pop("hyprconf.theme.version", None)
        write_json_inplace(settings_path, settings)
        return True
    return False


def get_status() -> dict:
    """Inspect all target editors and return status."""
    status = {}
    for key, info in TARGET_DEFINITIONS.items():
        exists = info["settings_path"].exists()
        synced = False
        if exists:
            data = read_json_lenient(info["settings_path"])
            synced = bool(data.get("hyprconf.theme.synced"))
        status[key] = {
            "name": info["name"],
            "installed": exists or info["settings_path"].parent.exists(),
            "settings_path": str(info["settings_path"]),
            "synced": synced
        }
    return status


def main():
    parser = argparse.ArgumentParser(description="Code Theme Synchronizer for Hyprconf")
    parser.add_argument("--sync", action="store_true", help="Sync active Hyprconf colors to enabled editors")
    parser.add_argument("--restore", action="store_true", help="Restore original editor themes and strip Hyprconf overrides")
    parser.add_argument("--status", action="store_true", help="Print detection and sync status for all editors")
    parser.add_argument("--enable", action="store_true", help="Enable the plugin")
    parser.add_argument("--disable", action="store_true", help="Disable the plugin and restore settings")
    parser.add_argument("--target", help="Specific target to sync/restore (e.g. antigravity, vscodium, vscode)")

    args = parser.parse_args()

    config = load_plugin_config()

    if args.enable:
        config["enabled"] = True
        save_plugin_config(config)
        print("code-theme-sync: Plugin enabled.")

    if args.disable:
        config["enabled"] = False
        save_plugin_config(config)
        for key, info in TARGET_DEFINITIONS.items():
            restore_editor_target(key, info)
        print("code-theme-sync: Plugin disabled and editor themes restored.")
        return

    if args.status:
        st = get_status()
        print(json.dumps(st, indent=2))
        return

    if args.restore:
        targets_to_restore = [args.target] if args.target else TARGET_DEFINITIONS.keys()
        for key in targets_to_restore:
            if key in TARGET_DEFINITIONS:
                restored = restore_editor_target(key, TARGET_DEFINITIONS[key])
                print(f"Restored {TARGET_DEFINITIONS[key]['name']}: {'Success' if restored else 'Skipped'}")
        return

    if not config.get("enabled", True):
        return

    colors = load_hyprconf_colors()
    active_targets = [args.target] if args.target else config.get("targets", ["antigravity", "vscodium", "vscode"])

    success_count = 0
    for key in active_targets:
        if key in TARGET_DEFINITIONS:
            synced = sync_editor_target(key, TARGET_DEFINITIONS[key], colors, config)
            if synced:
                success_count += 1
                print(f"[OK] Synced {TARGET_DEFINITIONS[key]['name']} to Terminal background ({colors.get('background', '#1d1513')}) and accent ({colors.get('accent', '#c47164')})")

    if success_count == 0 and not args.sync:
        print("No active editor targets found to sync.")


if __name__ == "__main__":
    main()
